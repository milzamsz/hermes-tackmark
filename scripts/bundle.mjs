/**
 * Bundle hermes-tackmark plugin for Hermes Desktop runtime loading.
 *
 * The Hermes runtime loader reads a single plugin.js file from disk, rewrites
 * bare specifiers (@hermes/plugin-sdk, react*) to shim blob URLs, then import()s
 * the blob. Relative imports (./core/session.js) cannot resolve from a blob URL,
 * so the multi-module source must be bundled into a single file first.
 *
 * esbuild handles this: it resolves and inlines all relative imports, preserves
 * bare specifiers as-is (they get rewritten by the loader), and outputs a single
 * ESM file with no external dependencies except @hermes/plugin-sdk and react.
 *
 * Usage: node scripts/bundle.mjs [--watch]
 */

import { build, context } from 'esbuild'
import { mkdir, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '..')
const entryPoint = join(repoRoot, 'src', 'plugin.js')
const outDir = join(repoRoot, 'dist')
const outFile = join(outDir, 'plugin.js')

/** Mark bare specifiers that the Hermes runtime loader rewrites to shim URLs.
 *  esbuild must treat these as external — NOT try to resolve them. */
const external = [
  '@hermes/plugin-sdk',
  'react',
  'react/jsx-runtime',
  'react/jsx-dev-runtime'
]

const buildOptions = {
  entryPoints: [entryPoint],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  outfile: outFile,
  external,
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  banner: {
    js: '// hermes-tackmark — bundled by esbuild. Source: src/plugin.js + src/core/*.js\n' +
         '// Do not edit this file directly — edit source and re-bundle.\n' +
         '// Bare specifiers (@hermes/plugin-sdk, react*) are resolved by the Hermes runtime loader.'
  }
}

async function main() {
  const watch = process.argv.includes('--watch')

  // Clean output
  await rm(outDir, { recursive: true, force: true })
  await mkdir(outDir, { recursive: true })

  if (watch) {
    const ctx = await context(buildOptions)
    await ctx.watch()
    console.log('[bundle] watching for changes →', outFile)
  } else {
    const result = await build(buildOptions)
    console.log('[bundle] OK →', outFile)
    console.log(`[bundle] ${result.warnings?.length ?? 0} warnings`)
  }
}

main().catch(err => {
  console.error('[bundle] FAILED:', err)
  process.exit(1)
})
